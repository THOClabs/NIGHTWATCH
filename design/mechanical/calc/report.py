def results_at_a_glance(results) -> str:
    rows = ["## 4. Results at a glance", "",
            "| # | Proof | Verdict | Governing number |", "|---|---|---|---|"]
    for num, r in results:
        rows.append(f"| {num} | {r.title} | {r.verdict.symbol} {r.verdict.value} | {r.headline} |")
    passes = sum(1 for _, r in results if r.verdict is Verdict.PASS)
    fails = sum(1 for _, r in results if r.verdict is Verdict.FAIL)
    marg = sum(1 for _, r in results if r.verdict is Verdict.MARGINAL)
    rows += ["",
             f"**{passes} PASS · {marg} MARGINAL · {fails} FAIL.** The FAILs are the value: each is a "
             "real gap in the repo's design that assertion had hidden — the bearing-limited stiffness, "
             "the sub-arcsec-incapable encoder chain, the missing survival-wind anchors, passive focus "
             "over the diurnal swing, and off-grid autonomy. Every FAIL carries a computed remedy below."]
    return "\n".join(rows)


def proof_section(num: str, r) -> str:
    parts = [f"### {num}. {r.title} — {r.verdict.symbol} {r.verdict.value}", "",
             f"**{r.headline}**", ""]
    if r.target:
        parts.append(f"*Target:* {r.target}  ")
    if r.safety_factor is not None:
        parts.append(f"*Governing safety factor:* {r.safety_factor:.2f}×")
    parts += ["", r.markdown_table(), ""]
    if r.assumptions:
        parts.append("_Assumptions:_")
        for a in r.assumptions:
            parts.append(f"- {a}")
        parts.append("")
    return "\n".join(parts)


def provenance_table() -> str:
    rows = ["## 6. Provenance ledger", "",
            "Where each key input comes from — the honesty table the repo lacks.", "",
            "| Parameter | Provenance | Source / basis |", "|---|:--:|---|"]
    for key, (prov, src) in P.PROVENANCE.items():
        rows.append(f"| `{key}` | **{prov.marker}** | {src} |")
    rows += ["", "**S** = sourced (repo file) · **D** = derived (computed) · **A** = assumed (repo silent)."]
    return "\n".join(rows)


