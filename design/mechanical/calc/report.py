def build_markdown() -> str:
    results = [(num, mod.evaluate()) for num, mod in PROOFS]
    blocks = [FRONT_MATTER.rstrip(), "", results_at_a_glance(results), "",
              "## 5. The proofs", ""]
    for num, r in results:
        blocks.append(proof_section(num, r))
    blocks.append(provenance_table())
    blocks.append("")
    # Trade study (section 7) and CAD (section 8): read the versioned narratives verbatim,
    # re-numbering their top heading into this document's outline.
    trade = TRADE_SECTION.read_text().strip()
    trade = trade.replace("## Trade Study (Phase B)", "## 7. Trade Study (Phase B)", 1)
    cad = CAD_SECTION.read_text().strip()
    cad = cad.replace("## Mechanical CAD (Phase D)", "## 8. Mechanical CAD (Phase D)", 1)
    blocks.append(trade)
    blocks.append("")
    blocks.append(cad)
    blocks.append("")
    blocks.append(SYNTHESIS.strip())
    text = "\n".join(b for b in blocks if b is not None)
    return text.rstrip() + "\n"


def main() -> None:
    OUT.write_text(build_markdown())
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
